"""
src/archive_results.py

Moves results of an older evaluation protocol out of the way before training,
so a machine that still holds an earlier run starts the current protocol
(utils.PROTOCOL) from a clean results/ folder. run_all.sh calls it first.

If raw_results.csv or any results/tables/parts/**.csv holds a row whose
`protocol` isn't the current one (rows from before the column existed count
as stale):
  1. results/tables, results/figures and results/preds are COPIED to
     results/archive/<timestamp>_before_<PROTOCOL>/ (nothing is lost);
  2. the result CSVs keep only current-protocol rows (part files left
     empty are removed), so a half-finished current run still resumes;
  3. derived outputs (tables, figures, efficiency.csv) are removed -- the
     profile / stats / evaluate steps regenerate them -- and so are the
     per-run predictions, unless current-protocol runs exist (their files
     share names with the old ones, and finished runs aren't retrained).
Nothing happens when every row already belongs to the current protocol.

    python -m src.archive_results            # archive if needed
    python -m src.archive_results --dry_run  # only report
"""

import argparse
import shutil
from datetime import datetime
from pathlib import Path

import pandas as pd

from src.merge_results import PARTS_DIR
from src.utils import PROTOCOL, RAW_RESULTS_CSV, RESULTS_DIR, PREDS_DIR

TABLES_DIR = RESULTS_DIR / "tables"
FIGURES_DIR = RESULTS_DIR / "figures"
ARCHIVE_DIR = RESULTS_DIR / "archive"
KEEP = {".gitkeep"}


def _result_csvs():
    files = [RAW_RESULTS_CSV] + (sorted(PARTS_DIR.rglob("*.csv")) if PARTS_DIR.exists() else [])
    return [f for f in files if f.exists() and f.stat().st_size > 0]


def _read(path: Path) -> pd.DataFrame:
    df = pd.read_csv(path, dtype=str, keep_default_na=False)
    if "protocol" not in df:
        df["protocol"] = ""
    return df


def _clear(directory: Path):
    """Remove everything in `directory` except .gitkeep."""
    if not directory.exists():
        return
    for p in directory.iterdir():
        if p.name in KEEP:
            continue
        shutil.rmtree(p) if p.is_dir() else p.unlink()


def archive_stale(dry_run: bool = False) -> bool:
    frames = {f: _read(f) for f in _result_csvs()}
    n_stale = sum(int((df["protocol"] != PROTOCOL).sum()) for df in frames.values())
    n_current = sum(int((df["protocol"] == PROTOCOL).sum()) for df in frames.values())
    if n_stale == 0:
        print(f"archive: results are all protocol '{PROTOCOL}' ({n_current} rows) -- nothing to archive")
        return False

    dest = ARCHIVE_DIR / f"{datetime.now():%Y-%m-%d_%H%M}_before_{PROTOCOL}"
    n = 2
    while dest.exists():  # never write into an earlier archive
        dest = ARCHIVE_DIR / f"{datetime.now():%Y-%m-%d_%H%M}_before_{PROTOCOL}_{n}"
        n += 1
    print(f"archive: {n_stale} rows from another protocol than '{PROTOCOL}' "
          f"({n_current} current rows are kept) -> copying results to {dest}")
    if dry_run:
        return True

    for src in (TABLES_DIR, FIGURES_DIR, PREDS_DIR):
        if src.exists():
            shutil.copytree(src, dest / src.name, ignore=shutil.ignore_patterns("*.lock"))
    (dest / "README.md").write_text(
        f"# Archive: results/ before a protocol-{PROTOCOL} run\n\n"
        f"Copied automatically by `src/archive_results.py` on {datetime.now():%Y-%m-%d %H:%M}, because "
        f"{n_stale} result rows were from another protocol than '{PROTOCOL}'. "
        f"See `docs/protocol_{PROTOCOL}.md`. Don't use these numbers in the paper.\n",
        encoding="utf-8")

    # keep only current-protocol rows in the result CSVs
    for path, df in frames.items():
        cur = df[df["protocol"] == PROTOCOL]
        if len(cur):
            cur.to_csv(path, index=False)
        else:
            path.unlink()
    # derived outputs are regenerated by the profile / stats / evaluate steps
    for p in TABLES_DIR.iterdir() if TABLES_DIR.exists() else []:
        if p.name in KEEP or p == RAW_RESULTS_CSV or p == PARTS_DIR:
            continue
        shutil.rmtree(p) if p.is_dir() else p.unlink()
    _clear(FIGURES_DIR)
    if n_current == 0:
        _clear(PREDS_DIR)
    print(f"archive: done; results/ now holds only protocol '{PROTOCOL}' runs ({n_current})")
    return True


if __name__ == "__main__":
    p = argparse.ArgumentParser(description="Archive results from an older evaluation protocol.")
    p.add_argument("--dry_run", action="store_true", help="only report what would be archived")
    archive_stale(p.parse_args().dry_run)
